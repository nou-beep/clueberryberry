/**
 * Curated word + clue banks for the Playground generator.
 *
 * These are the only source of Playground content: there is no model and no
 * network call anywhere in this feature. Every entry carries 2–3 alternative
 * clues so re-rolling the same word gives a different clue, and a 1–5
 * difficulty rating used to bias selection.
 *
 * Editorial rules (docs/authoring-guide.md): clues are 2–9 words, never
 * restate or contain the answer, and are factually true. Answers are single
 * words, 3–9 cells; French answers are uppercase and unaccented; Arabic
 * answers carry no diacritics and use natural spelling.
 *
 * Tags drive the player-facing option controls:
 *   properNoun    — a name (person, place, title, brand)
 *   abbreviation  — an acronym or shortened form
 *   sensitive     — excluded when family-friendly mode is on
 *
 * On the World War II banks: they cover the military, political, technical and
 * home-front record only. The Holocaust is deliberately absent — it belongs to
 * hand-authored, sourced puzzles in the `ww2-holocaust` collection, not to a
 * generator shuffling a word bank.
 *
 * On the fandom banks (Taylor Swift, One Direction): song titles, album names
 * and publicly reported career facts only. No lyrics, in any quantity, ever.
 */

