/** Themes with a bank in the given language, in display order. */
export function themesFor(language: PuzzleLanguage): PlaygroundTheme[] {
  return PLAYGROUND_THEMES.filter((theme) => (BANKS[language][theme] ?? []).length > 0);
}

export function bankFor(language: PuzzleLanguage, theme: PlaygroundTheme): BankWord[] {
  return BANKS[language][theme] ?? [];
}

/** Subject slugs that have at least one themed bank in this language. */
export function subjectsFor(language: PuzzleLanguage): string[] {
  const seen: string[] = [];
  for (const theme of themesFor(language)) {
    const { subject } = THEME_META[theme];
    if (!seen.includes(subject)) seen.push(subject);
  }
  return seen;
}

/** Themes of one subject that have a bank in this language. */
export function themesForSubject(
  language: PuzzleLanguage,
  subject: string
): PlaygroundTheme[] {
  return themesFor(language).filter((theme) => THEME_META[theme].subject === subject);
}

/** The theme whose collection slug matches, if it has a bank in this language. */
export function themeForCollection(
  language: PuzzleLanguage,
  collection: string
): PlaygroundTheme | null {
  return (
    themesFor(language).find((theme) => THEME_META[theme].collection === collection) ?? null
  );
}
