export type PlaygroundTheme = (typeof PLAYGROUND_THEMES)[number];

export type WordDifficulty = 1 | 2 | 3 | 4 | 5;

export interface BankWord {
  answer: string;
  clues: string[];
  difficulty: WordDifficulty;
  /** A name: person, place, title or brand. */
  properNoun?: boolean;
  /** An acronym or a shortened form. */
  abbreviation?: boolean;
  /** Unsuitable for a family-friendly puzzle (violence, death, warfare). */
  sensitive?: boolean;
  /** Genuine spelling variants, same cell count as the answer. */
  alternatives?: string[];
  /** One factual line, shown as the answer explanation after solving. */
  note?: string;
}

type Bank = Partial<Record<PlaygroundTheme, BankWord[]>>;

const w = (
  answer: string,
  difficulty: WordDifficulty,
  ...clues: string[]
): BankWord => ({ answer, clues, difficulty });

/** Tag helpers — composable, e.g. `pn(ab(w("NASA", 2, "…")))`. */
const pn = (word: BankWord): BankWord => ({ ...word, properNoun: true });
const ab = (word: BankWord): BankWord => ({ ...word, abbreviation: true });
const sv = (word: BankWord): BankWord => ({ ...word, sensitive: true });
const alt = (word: BankWord, ...alternatives: string[]): BankWord => ({
  ...word,
  alternatives,
});
const nt = (word: BankWord, note: string): BankWord => ({ ...word, note });

